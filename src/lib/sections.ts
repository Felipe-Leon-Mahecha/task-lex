export function makeSectionId(label: string, existing: string[]): string {
  const base =
    label
      .toLowerCase()
      .normalize('NFD')
      .replace(/[\u0300-\u036f]/g, '')
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 24) || 'apartado'
  let id = base
  let i = 2
  while (existing.includes(id)) id = `${base}-${i++}`
  return id
}
